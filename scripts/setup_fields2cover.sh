#!/usr/bin/env bash
# Install the pinned Fields2Cover dependency for ROS 2 Humble inside Docker.
set -euo pipefail

repo_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
dependency_root="$repo_root/.deps"
upstream_url="https://github.com/Fields2Cover/Fields2Cover.git"
upstream_revision=8bf28f7c5b6d8b8a2688aaa8fb1ac426e5c2d942
version_root="$dependency_root/fields2cover-humble-$upstream_revision"
source_dir="$version_root/src"
build_dir="$version_root/build"
install_dir="$version_root/install"
jobs=2

usage() {
  cat <<'EOF'
Usage: scripts/setup_fields2cover.sh [--jobs N] [--ros-distro humble]

Build Fields2Cover v1.2.1 under .deps/ without sudo or global installation.
Enter the Humble container through /home/hucheng/shell/navigation_sim.sh first.
Initial setup downloads pinned dependencies from GitHub.
--jobs defaults to 2; only ROS 2 Humble is supported.
EOF
}

while (($#)); do
  case "$1" in
    --ros-distro)
      if (($# < 2)) || [[ "$2" != humble ]]; then
        echo 'ERROR: Only --ros-distro humble is supported.' >&2
        exit 2
      fi
      shift 2
      ;;
    --jobs)
      if (($# < 2)) || [[ ! "$2" =~ ^[1-9][0-9]*$ ]]; then
        echo 'ERROR: --jobs requires a positive integer.' >&2
        exit 2
      fi
      jobs="$2"
      shift 2
      ;;
    -h|--help) usage; exit 0 ;;
    *) echo "ERROR: Unknown argument: $1" >&2; usage >&2; exit 2 ;;
  esac
done

if [[ ! -f /.dockerenv ]]; then
  echo 'ERROR: Enter Docker through /home/hucheng/shell/navigation_sim.sh first.' >&2
  exit 1
fi
if [[ -n "${ROS_DISTRO:-}" && "$ROS_DISTRO" != humble ]]; then
  echo 'ERROR: Source /opt/ros/humble/setup.bash before compiling.' >&2
  exit 1
fi

# matplotlib-cpp is fetched by upstream even when tutorials/Python are disabled.
required_packages=(
  build-essential ca-certificates cmake git libeigen3-dev libgdal-dev
  libgeos-dev python3-dev python3-numpy python3-matplotlib python3-tk
)
missing_packages=()
for package in "${required_packages[@]}"; do
  if [[ "$(dpkg-query -W -f='${Status}' "$package" 2>/dev/null || true)" != 'install ok installed' ]]; then
    missing_packages+=("$package")
  fi
done
if ((${#missing_packages[@]})); then
  printf 'ERROR: Missing prerequisite packages: %s\n' "${missing_packages[*]}" >&2
  printf 'Install them separately, then rerun:\n  sudo apt-get install --no-install-recommends' >&2
  printf ' %q' "${missing_packages[@]}" >&2
  printf '\n' >&2
  exit 1
fi

mkdir -p "$version_root"
# Keep colcon from discovering the third-party source as another ROS package.
touch "$dependency_root/COLCON_IGNORE"
if [[ ! -e "$source_dir" ]]; then
  git clone --branch v1.2.1 --single-branch "$upstream_url" "$source_dir"
fi
if [[ ! -d "$source_dir/.git" ]]; then
  echo "ERROR: $source_dir exists but is not a Git checkout." >&2
  exit 1
fi
if [[ "$(git -C "$source_dir" remote get-url origin)" != "$upstream_url" ]]; then
  echo "ERROR: Unexpected origin in $source_dir; refusing to modify it." >&2
  exit 1
fi
if [[ "$(git -C "$source_dir" rev-parse HEAD)" != "$upstream_revision" ]]; then
  echo "ERROR: $source_dir must use pinned v1.2.1 revision $upstream_revision." >&2
  exit 1
fi

# Upstream hardcodes registry export ON; disable it to avoid writing ~/.cmake.
sed -i 's/^set(CMAKE_EXPORT_PACKAGE_REGISTRY ON)$/set(CMAKE_EXPORT_PACKAGE_REGISTRY OFF)/' \
  "$source_dir/CMakeLists.txt"

cmake -S "$source_dir" -B "$build_dir" \
  -DCMAKE_BUILD_TYPE=Release \
  -DCMAKE_INSTALL_PREFIX="$install_dir" \
  -DINSTALL_CMAKE_DIR=lib/ \
  -DCMAKE_EXPORT_PACKAGE_REGISTRY=OFF \
  -DCMAKE_EXPORT_NO_PACKAGE_REGISTRY=ON \
  -DCMAKE_FIND_USE_PACKAGE_REGISTRY=OFF \
  -DFETCHCONTENT_UPDATES_DISCONNECTED=ON \
  -DBUILD_TESTING=OFF \
  -Dtinyxml2_BUILD_TESTING=OFF \
  -DBUILD_TESTS=OFF \
  -DBUILD_TUTORIALS=OFF \
  -DBUILD_PYTHON=OFF \
  -DBUILD_DOC=OFF \
  -DALLOW_PARALLELIZATION=OFF
cmake --build "$build_dir" --parallel "$jobs"
cmake --install "$build_dir"

config_dir="$install_dir/lib/cmake/fields2cover"
if [[ ! -f "$config_dir/Fields2CoverConfig.cmake" ]]; then
  echo "ERROR: Fields2CoverConfig.cmake was not installed in $config_dir." >&2
  exit 1
fi
cat > "$dependency_root/fields2cover-env.bash" <<EOF
# Generated by scripts/setup_fields2cover.sh. Source this file before colcon.
export OPENNAV_COVERAGE_FIELDS2COVER_ROS_DISTRO=humble
EOF
printf '_coverage_f2c_prefix=%q\n' "$install_dir" >> "$dependency_root/fields2cover-env.bash"
cat >> "$dependency_root/fields2cover-env.bash" <<'EOF'
export Fields2Cover_DIR="$_coverage_f2c_prefix/lib/cmake/fields2cover"
export CMAKE_PREFIX_PATH="$_coverage_f2c_prefix${CMAKE_PREFIX_PATH:+:$CMAKE_PREFIX_PATH}"
export LD_LIBRARY_PATH="$_coverage_f2c_prefix/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
unset _coverage_f2c_prefix
EOF
printf '\nFields2Cover %s installed locally.\n' "$upstream_revision"
printf 'Fields2Cover_DIR=%s\n' "$config_dir"
printf 'CMAKE_PREFIX_PATH entry: %s\n' "$install_dir"
printf 'Runtime library directory: %s\n' "$install_dir/lib"
printf 'Environment: source %q\n' "$dependency_root/fields2cover-env.bash"
